it('contains keyboard focus and preserves the file and reading position while Escape restores then closes', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => response()))
  render(<><button type="button">外部操作</button><SkillsCenter t={t} /></>)
  const opener = (await waitForCatalog())[0]!
  fireEvent.click(opener)
  const dialog = screen.getByRole('dialog')
  const first = within(dialog).getByRole('button', { name: '下载整个 Skill' })
  fireEvent.keyDown(document.activeElement!, { key: 'Tab' })
  expect(document.activeElement).toBe(first)
  fireEvent.click(within(dialog).getByRole('button', { name: 'LICENSE' }))
  const last = within(dialog).getByRole('button', { name: '下载当前文件' })
  first.focus()
  fireEvent.keyDown(first, { key: 'Tab', shiftKey: true })
  expect(document.activeElement).toBe(last)
  fireEvent.keyDown(last, { key: 'Tab' })
  expect(document.activeElement).toBe(first)
  screen.getByRole('button', { name: '外部操作' }).focus()
  expect(dialog.contains(document.activeElement)).toBe(true)

  const body = dialog.querySelector<HTMLElement>('[data-skill-file="LICENSE"]')!
  body.scrollTop = 84
  fireEvent.click(within(dialog).getByRole('button', { name: '放大阅读' }))
  expect(within(dialog).getByRole('button', { name: '还原窗口' }).getAttribute('aria-pressed')).toBe('true')
  expect(dialog.querySelector('[data-skill-file="LICENSE"]')).toBe(body)
  expect(body.scrollTop).toBe(84)
  fireEvent.keyDown(within(dialog).getByRole('button', { name: '还原窗口' }), { key: 'Escape' })
  expect(screen.getByRole('dialog')).toBe(dialog)
  expect(within(dialog).getByRole('button', { name: '放大阅读' }).getAttribute('aria-pressed')).toBe('false')
  expect(body.scrollTop).toBe(84)
  fireEvent.keyDown(within(dialog).getByRole('button', { name: '放大阅读' }), { key: 'Escape' })
  expect(screen.queryByRole('dialog')).toBeNull()
  expect(document.activeElement).toBe(opener)
})

it('closes from the mask and releases modal locks on unmount without clearing earlier background state', async () => {
  vi.stubGlobal('fetch', vi.fn(async () => response()))
  const inactive = document.createElement('div')
  inactive.setAttribute('inert', 'existing')
  document.body.append(inactive)
  const overflow = document.body.style.overflow
  document.body.style.overflow = 'scroll'
  try {
    const view = render(<SkillsCenter t={t} />)
    const openers = await waitForCatalog()
    fireEvent.click(openers[0]!)
    expect(document.body.style.overflow).toBe('hidden')
    const dialog = screen.getByRole('dialog')
    fireEvent.click(dialog.parentElement!.querySelector('[aria-hidden="true"]')!)
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(document.body.style.overflow).toBe('scroll')
    expect(inactive.getAttribute('inert')).toBe('existing')
    fireEvent.click(openers[1]!)
    expect(screen.getByRole('dialog', { name: '项目启动与方向确认' }).querySelector('[data-skill-file="SKILL.md"]')).not.toBeNull()
    view.unmount()
    expect(view.container.hasAttribute('inert')).toBe(false)
    expect(inactive.getAttribute('inert')).toBe('existing')
    expect(document.body.style.overflow).toBe('scroll')
  } finally {
    cleanup()
    inactive.remove()
    document.body.style.overflow = overflow
  }
})

